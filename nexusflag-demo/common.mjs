// Shared helpers for the NexusFlag demo scripts: arg parsing, .env.demo I/O, a tiny Core API client.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

export const HERE = dirname(fileURLToPath(import.meta.url));
export const ENV_FILE = join(HERE, '.env.demo');
export const SHOP_DIR = join(HERE, '..');

/** `--key value` and `--flag` parsing. Positionals are returned in `_`. */
export function parseArgs(argv) {
  const out = { _: [] };
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a.startsWith('--')) {
      const eq = a.indexOf('=');
      if (eq > 0) { out[a.slice(2, eq)] = a.slice(eq + 1); continue; }
      const next = argv[i + 1];
      if (next !== undefined && !next.startsWith('--')) { out[a.slice(2)] = next; i++; } else out[a.slice(2)] = true;
    } else out._.push(a);
  }
  return out;
}

export function readEnvFile(file = ENV_FILE) {
  if (!existsSync(file)) return undefined;
  const env = {};
  for (const line of readFileSync(file, 'utf8').split(/\r?\n/)) {
    const m = /^\s*([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(.*?)\s*$/.exec(line);
    if (m && !line.trim().startsWith('#')) env[m[1]] = m[2];
  }
  return env;
}

export function writeEnvFile(values, file = ENV_FILE) {
  const body = Object.entries(values).map(([k, v]) => `${k}=${v}`).join('\n');
  writeFileSync(file, `# Generated by provision.mjs. Contains secrets; gitignored.\n${body}\n`, { mode: 0o600 });
}

export const mask = (s) => (typeof s === 'string' && s.length > 8 ? `${s.slice(0, 6)}...(${s.length} chars)` : '***');

export class CoreError extends Error {
  constructor(status, method, path, body) {
    super(`Core ${method} ${path} -> ${status}: ${typeof body === 'string' ? body : JSON.stringify(body)}`);
    this.status = status; this.body = body;
  }
}

/** Core API client: bearer token from /auth/login, Origin header must equal Core's DASHBOARD_ORIGIN. */
export class Core {
  constructor({ core, origin, email, password }) {
    Object.assign(this, { core, origin, email, password });
    this.token = undefined;
  }
  async send(method, path, body, bearer = true) {
    const headers = { accept: 'application/json', origin: this.origin };
    if (body !== undefined) headers['content-type'] = 'application/json';
    if (bearer && this.token) headers.authorization = `Bearer ${this.token}`;
    let res;
    try {
      res = await fetch(new URL(path, this.core), { method, headers, body: body === undefined ? undefined : JSON.stringify(body), signal: AbortSignal.timeout(15000) });
    } catch (e) {
      throw new Error(`Core ${method} ${path} unreachable (${e.cause?.code ?? e.message}). Is core-api running at ${this.core}?`);
    }
    const text = await res.text();
    let parsed = text;
    if (text) { try { parsed = JSON.parse(text); } catch { /* keep text */ } } else parsed = undefined;
    if (!res.ok) throw new CoreError(res.status, method, path, parsed);
    return parsed;
  }
  async authenticate(log = () => {}) {
    const creds = { schemaVersion: 1, email: this.email, password: this.password };
    const login = async () => {
      const r = await this.send('POST', '/auth/login', creds, false);
      if (!r?.accessToken) throw new Error('login response had no accessToken');
      this.token = r.accessToken;
    };
    try { await login(); log('POST /auth/login ok'); return; } catch (e) {
      if (!(e instanceof CoreError) || ![400, 401, 404].includes(e.status)) throw e;
    }
    await this.send('POST', '/auth/signup', creds, false);
    log('POST /auth/signup ok (new account)');
    await login();
    log('POST /auth/login ok');
  }
  async call(method, path, body) {
    if (!this.token) await this.authenticate();
    try { return await this.send(method, path, body); } catch (e) {
      if (e instanceof CoreError && e.status === 401) { await this.authenticate(); return this.send(method, path, body); }
      throw e;
    }
  }
  get(p) { return this.call('GET', p); }
  post(p, b) { return this.call('POST', p, b); }
}

/** Build a Core client from .env.demo (for flag.mjs). */
export function coreFromEnvFile(args) {
  const env = readEnvFile();
  if (!env) { console.error('nexusflag-demo/.env.demo not found. Run `node provision.mjs` first.'); process.exit(2); }
  const need = ['DEMO_CORE_URL', 'DEMO_ORIGIN', 'DEMO_ADMIN_EMAIL', 'DEMO_ADMIN_PASSWORD', 'DEMO_WORKSPACE_ID', 'DEMO_PROJECT_ID', 'DEMO_ENVIRONMENT_ID', 'DEMO_FLAG_ID'];
  for (const k of need) if (!env[k]) { console.error(`.env.demo is missing ${k}; re-run provision.mjs`); process.exit(2); }
  const core = new Core({ core: args.core ?? env.DEMO_CORE_URL, origin: args.origin ?? env.DEMO_ORIGIN, email: env.DEMO_ADMIN_EMAIL, password: env.DEMO_ADMIN_PASSWORD });
  return { env, core };
}
